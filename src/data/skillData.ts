export function getSkillsForMecha(mechaType: MechaType): SkillData[] {
  return SKILL_DATABASE.filter((s) => s.mechaType === mechaType);
}

export function getAvailableSkills(mechaType: MechaType, playerLevel: number): SkillData[] {
  return SKILL_DATABASE.filter((s) => s.mechaType === mechaType && s.level <= playerLevel);
}

export const LEARNING_MODE_SKILL_NOTICE = 'Learning edition: Tianjian skills unlocked for practice';

export function getPlayableSkills(mechaType: MechaType, playerLevel: number, learningModeUnlock: boolean = true): SkillData[] {
  return SKILL_DATABASE.filter((skill) => {
    if (skill.mechaType !== mechaType) return false;
    if (skill.level <= playerLevel) return true;

    return learningModeUnlock
      && mechaType === MechaType.TIAN_JIAN
      && (skill.type === SkillType.SPECIAL || skill.type === SkillType.ULTIMATE);
  });
}
